window.getShopifyProductUrl = function getShopifyProductUrl(product) {
  if (product.shopifyProductUrl) {
    return product.shopifyProductUrl;
  }

  if (window.SHOPIFY_STORE_DOMAIN && product.shopifyHandle) {
    return `https://${window.SHOPIFY_STORE_DOMAIN}/products/${product.shopifyHandle}`;
  }

  return "";
};

window.getShopifyCartUrl = function getShopifyCartUrl(product, option = "Puzzle", quantity = 1) {
  const variantId = product.variants && product.variants[option];

  if (!window.SHOPIFY_STORE_DOMAIN || !variantId) {
    return "";
  }

  return `https://${window.SHOPIFY_STORE_DOMAIN}/cart/${variantId}:${quantity}`;
};

window.getShopifyCheckoutUrl = function getShopifyCheckoutUrl(product, option = "Puzzle") {
  return window.getShopifyProductUrl(product) || window.getShopifyCartUrl(product, option);
};
